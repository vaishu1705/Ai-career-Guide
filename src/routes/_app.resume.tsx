import { createFileRoute } from "@tanstack/react-router";
import { Download, FileText } from "lucide-react";
import { useEffect, useState } from "react";
import jsPDF from "jspdf";
import { journey } from "@/lib/journey-store";
import { roadmapFor, moduleCompleted } from "@/lib/roadmaps";

export const Route = createFileRoute("/_app/resume")({
  component: ResumeBuilder,
});

function ResumeBuilder() {
  const [form, setForm] = useState({
    name: "Aarya Rao", email: "aarya@example.com", phone: "+91 98765 43210",
    college: "IIT Bombay", branch: "Computer Science", year: "3rd Year", cgpa: "8.7",
    summary: "Motivated engineering student passionate about building AI-powered products.",
  });
  const [prediction, setPrediction] = useState<any>(null);
  const [progress, setProgress] = useState<Record<string, any>>({});
  const [skills, setSkills] = useState<string>("Python, JavaScript, React, SQL, Machine Learning");

  useEffect(() => {
    const p = journey.getProfile();
    setForm(f => ({ ...f, ...p, cgpa: p.cgpa ?? f.cgpa, name: p.name ?? f.name, email: p.email ?? f.email }));
    setPrediction(journey.getPrediction());
    setProgress(journey.getProgress());
  }, []);

  const completedModules = prediction
    ? roadmapFor(prediction.careerSlug).filter(m => moduleCompleted(progress[m.id]))
    : [];
  const certs = Object.values(progress).filter((p: any) => p?.certificateId);

  const download = () => {
    const pdf = new jsPDF({ unit: "pt", format: "a4" });
    const w = pdf.internal.pageSize.getWidth();
    let y = 60;
    pdf.setFillColor(79, 70, 229); pdf.rect(0, 0, w, 100, "F");
    pdf.setTextColor(255); pdf.setFont("helvetica", "bold"); pdf.setFontSize(24);
    pdf.text(form.name, 40, 55);
    pdf.setFont("helvetica", "normal"); pdf.setFontSize(11);
    pdf.text(`${form.email}  |  ${form.phone}`, 40, 80);
    pdf.setTextColor(20); y = 130;

    const section = (title: string) => {
      pdf.setFont("helvetica", "bold"); pdf.setFontSize(13); pdf.setTextColor(79, 70, 229);
      pdf.text(title.toUpperCase(), 40, y); y += 6;
      pdf.setDrawColor(220); pdf.line(40, y, w - 40, y); y += 16;
      pdf.setTextColor(20); pdf.setFont("helvetica", "normal"); pdf.setFontSize(11);
    };
    const line = (txt: string) => {
      const lines = pdf.splitTextToSize(txt, w - 80);
      pdf.text(lines, 40, y); y += lines.length * 14;
    };

    section("Summary"); line(form.summary); y += 8;
    section("Education"); line(`${form.college} — ${form.branch}, ${form.year} (CGPA ${form.cgpa})`); y += 8;
    section("Career Goal"); line(prediction?.careerTitle ? `Aspiring ${prediction.careerTitle}` : "Aspiring Software Engineer"); y += 8;
    section("Skills"); line(skills); y += 8;
    if (completedModules.length) {
      section("Completed Learning Modules");
      completedModules.forEach(m => { line(`• ${m.title} (${m.level})`); });
      y += 8;
    }
    if (certs.length) {
      section("Certifications");
      certs.forEach((c: any) => line(`• ${c.moduleId.toUpperCase()} — Cert ${c.certificateId}`));
    }
    pdf.setFontSize(9); pdf.setTextColor(120);
    pdf.text("Generated by AI Career Guide Resume Builder", 40, pdf.internal.pageSize.getHeight() - 24);
    pdf.save(`resume-${form.name.toLowerCase().replace(/\s+/g, "-")}.pdf`);
  };

  const field = (k: keyof typeof form, l: string) => (
    <div>
      <label className="text-sm font-medium">{l}</label>
      <input value={form[k]} onChange={e => setForm(s => ({ ...s, [k]: e.target.value }))}
        className="mt-1.5 w-full h-11 px-3 rounded-xl border border-input bg-background outline-none focus:ring-2 focus:ring-primary/40" />
    </div>
  );

  return (
    <div className="space-y-6">
      <header className="flex items-center justify-between">
        <div>
          <h1 className="font-display text-2xl font-bold">AI Resume Builder</h1>
          <p className="text-muted-foreground">Auto-fills from your profile and progress.</p>
        </div>
        <button onClick={download} className="inline-flex items-center gap-2 px-5 h-11 rounded-xl bg-gradient-primary text-primary-foreground font-semibold shadow-soft">
          <Download className="h-4 w-4" /> Download PDF
        </button>
      </header>

      <div className="grid lg:grid-cols-2 gap-6">
        <div className="rounded-2xl p-6 bg-card border border-border shadow-card space-y-4">
          <div className="grid sm:grid-cols-2 gap-4">
            {field("name", "Full name")} {field("email", "Email")}
            {field("phone", "Phone")} {field("college", "College")}
            {field("branch", "Branch")} {field("year", "Year")}
            {field("cgpa", "CGPA")}
          </div>
          <div>
            <label className="text-sm font-medium">Summary</label>
            <textarea value={form.summary} onChange={e => setForm(s => ({ ...s, summary: e.target.value }))} rows={3}
              className="mt-1.5 w-full px-3 py-2 rounded-xl border border-input bg-background outline-none focus:ring-2 focus:ring-primary/40" />
          </div>
          <div>
            <label className="text-sm font-medium">Skills (comma-separated)</label>
            <textarea value={skills} onChange={e => setSkills(e.target.value)} rows={2}
              className="mt-1.5 w-full px-3 py-2 rounded-xl border border-input bg-background outline-none focus:ring-2 focus:ring-primary/40" />
          </div>
        </div>

        <div className="rounded-2xl p-8 bg-white text-gray-900 shadow-card border border-border overflow-hidden">
          <div className="border-b-2 border-primary pb-3">
            <h2 className="font-display text-2xl font-bold text-primary">{form.name}</h2>
            <p className="text-xs">{form.email} · {form.phone}</p>
          </div>
          <section className="mt-4">
            <h3 className="text-xs font-bold uppercase text-primary">Summary</h3>
            <p className="text-sm mt-1">{form.summary}</p>
          </section>
          <section className="mt-4">
            <h3 className="text-xs font-bold uppercase text-primary">Education</h3>
            <p className="text-sm mt-1">{form.college} — {form.branch}, {form.year} (CGPA {form.cgpa})</p>
          </section>
          <section className="mt-4">
            <h3 className="text-xs font-bold uppercase text-primary">Career Goal</h3>
            <p className="text-sm mt-1">Aspiring {prediction?.careerTitle ?? "Software Engineer"}</p>
          </section>
          <section className="mt-4">
            <h3 className="text-xs font-bold uppercase text-primary">Skills</h3>
            <p className="text-sm mt-1">{skills}</p>
          </section>
          {completedModules.length > 0 && (
            <section className="mt-4">
              <h3 className="text-xs font-bold uppercase text-primary">Completed Modules</h3>
              <ul className="text-sm mt-1 list-disc pl-5">
                {completedModules.map(m => <li key={m.id}>{m.title} ({m.level})</li>)}
              </ul>
            </section>
          )}
          {certs.length > 0 && (
            <section className="mt-4">
              <h3 className="text-xs font-bold uppercase text-primary">Certifications</h3>
              <ul className="text-sm mt-1 list-disc pl-5">
                {certs.map((c: any) => <li key={c.certificateId}>Certificate {c.certificateId}</li>)}
              </ul>
            </section>
          )}
          <div className="mt-6 pt-3 border-t text-[10px] text-gray-500 flex items-center gap-1.5">
            <FileText className="h-3 w-3" /> Generated by AI Career Guide
          </div>
        </div>
      </div>
    </div>
  );
}
